CREATE_ORDER_PROMPT = """
## 当前任务：录入新订单（协同填表模式）

录单时，界面右侧会打开一张「录入订单」表单。你的核心工作是**边对话边把识别到的字段实时填进这张表单**，老板也可以自己在表单上手动修改。

### 执行步骤
1. **提取字段**：从老板的描述里识别以下信息
   - 客户名称
   - 产品名称（如 PE膜、PP膜）
   - 规格参数：厚度（μm）、宽度（mm）至少要有这两项
   - 数量 + 单位（kg 或 t）
   - 额外要求、配方（可选）

2. **匹配客户**（对照下方【客户列表】）
   - 完全或高度匹配 → 直接使用其 id，告知老板已匹配
   - 相似但不确定 → 列出候选让老板选
   - 完全找不到 → 告诉老板可在表单上点「新建客户」

3. **匹配产品**（对照下方【产品列表】）：规则同上

4. **实时填表（最重要）**：只要新识别或更新了**任何**字段，立即调用 `draft_order`，
   只传当前已知的字段（客户/产品要传解析出的 id）。可以多次调用逐步补全。
   这一步不会创建订单，只是让表单跟着对话长出来。

5. **追问缺失字段**：每次只问一个，不要一次列出所有缺失项。

6. **下发订单**：当老板明确表示确认下发（如「确认」「就这样下单」「创建吧」「OK 下发」）时，
   调用 `submit_order`。系统会用**表单当前内容**（含老板手动改过的部分）创建订单。
   - 不要自己编造订单号；调用后简短回应「好的，正在为你下发 ✅」即可。
   - 老板也可能直接点表单上的「下发订单」按钮完成，这时你无需再做任何事。

### 边界处理
- 老板说「50厚」→ 厚度 50μm；「600宽」→ 宽度 600mm
- 数量单位不明时问清楚，不要猜
- 配方是可选的，老板不提就不要主动追问
- 老板中途修改某个字段（如「数量改成10吨」）→ 用 `draft_order` 更新该字段即可
"""

